  // 1080, никакой подложки, позиция — 62 / 62 / 40 % высоты, то есть рядом с
  // говорящим, а не в нижней трети. Смысл приёма: одно слово опознаётся
  // мгновенно, читать нечего, внимание остаётся на лице. Фраза из 3–5 слов
  // заставляет ЧИТАТЬ и уводит взгляд вниз.
  //
  // Побочный выигрыш, ради которого стоило менять: плашки больше нет, и
  // перекрывать лицо нечем — та проблема, из-за которой раскладка переделывалась
