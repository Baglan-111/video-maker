// Токены шаблона promo@1 — три уровня (design-foundations, правило 3).
//
// Уровень 1 (primitive) — сырые значения: hex, числа шкал. Компоненты его НЕ
// читают напрямую, он существует только чтобы уровень 2 не изобретал числа.
// Уровень 2 (semantic) — «что это значит»: цвет чернил, цвет поверхности,
// шаг отступа, шаг кегля.
// Уровень 3 (component) — «сколько именно у этой детали»: паддинг карточки,
// высота строки списка, размер курсора.
//
// Смысл разделения: сменить акцент ролика = поменять одно значение на уровне 2.
// В promo@1 акцент к тому же приходит извне (accent из video.json), поэтому
// семантический слой собирается функцией semantic(accent), а не константой.
//
// ── Зафиксированный субстрат (объявлено до первой строки разметки) ───────────
// Шкала отступов, база 8: 8, 16, 24, 32, 48, 64, 96, 128, 160. Иных значений нет.
// Шкала кегля (шаги IBM Carbon): 24, 32, 36, 42, 68, 92. Иных значений нет.
// Веса: 400 и 700 — два из трёх разрешённых.
// Контраст: текст ≥ 4.5:1, крупный текст (≥42, вес 700) ≥ 3:1, границы ≥ 3:1
//   относительно заливки, которую они очерчивают. Числа посчитаны, см. CONTRAST.
//
// Осознанно неприменимо для медиума «видео» (правило скилла: сказать вслух,
// а не пропустить молча):
//   • rem вместо px — в кадре 1920×1080 нет пользовательского зума, единица
//     измерения фиксирована навсегда; px здесь и есть логическая единица;
//   • размер целей нажатия и видимость фокуса — в ролике нечего нажимать;
//   • prefers-reduced-motion — у mp4 нет доступа к настройкам системы.

// ── Уровень 1: примитивы ─────────────────────────────────────────────────────
const primitive = {
  // Палитра. Светлая, как у эталонного продуктового промо: холодный градиент
  // от почти белого к бледно-синему, белая карточка поверх.
  white: '#FFFFFF',
  ink900: '#0F1419',
  ink600: '#4A5261',
  steel400: '#7F8FA8',
  steel200: '#C2CCDB',
  sky050: '#F7F9FC',
  sky200: '#C9D8F0',

  // Шкала отступов, база 8.
  space: [8, 16, 24, 32, 48, 64, 96, 128, 160],
  // Шкала кегля, шаги Carbon.
  fontSize: [24, 32, 36, 42, 68, 92],
  weight: { regular: 400, bold: 700 },
  radius: { card: 24, pill: 999 },
} as const;

// ── Измеренный контраст (WCAG 2.2, формула относительной яркости) ────────────
// Значения проверены расчётом, а не на глаз; порог рядом с каждым.
export const CONTRAST = {
  'ink900 / white (текст карточки)': { ratio: 18.51, min: 4.5 },
  'ink900 / sky050 (заголовок, верх фона)': { ratio: 17.55, min: 3 },
  'ink900 / sky200 (заголовок, низ фона)': { ratio: 12.84, min: 3 },
  'accent / white (акцент на карточке)': { ratio: 6.87, min: 4.5 },
  'accent / sky050 (акцент заголовка, верх)': { ratio: 6.51, min: 3 },
  'accent / sky200 (акцент заголовка, низ)': { ratio: 4.76, min: 3 },
  'ink600 / white (подпись счётчика)': { ratio: 7.86, min: 4.5 },
  'white / ink900 (текст плашки-субтитра)': { ratio: 18.51, min: 4.5 },
  'white / accent (цифра в бейдже)': { ratio: 6.87, min: 4.5 },
  'steel400 / white (граница карточки к её заливке)': { ratio: 3.28, min: 3 },
} as const;
// Замечание про границу карточки: 3.28:1 посчитано против белой заливки, которую
// граница очерчивает, — против фона страницы там 2.28:1. Так и в эталоне: белая
// карточка на светлом фоне держится границей и тенью, а не разностью заливок.
// Число названо явно, чтобы это было решением, а не недосмотром.
// Значение accent берётся из video.json; расчёты выше сделаны для #2450C8,
// который стоит в projects/promo-kartoteka/video.json.

// ── Уровень 2: семантика ─────────────────────────────────────────────────────
export const semantic = (accent: string) =>
  ({
    color: {
      pageTop: primitive.sky050,
      pageBottom: primitive.sky200,
      surface: primitive.white,
      surfaceBorder: primitive.steel400,
      hairline: primitive.steel200,
      textPrimary: primitive.ink900,
      textMuted: primitive.ink600,
      textAccent: accent,
      textOnAccent: primitive.white,
      textOnScrim: primitive.white,
      accentFill: accent,
      scrim: primitive.ink900,
      cursor: primitive.ink900,
    },
    space: {
      hair: primitive.space[0], //   8 — внутри мелкой детали
      tight: primitive.space[1], //  16 — между строкой и её подписью
      snug: primitive.space[2], //   24 — внутри бейджа
      normal: primitive.space[3], // 32 — между блоками внутри карточки
      loose: primitive.space[4], //  48 — внутренние поля карточки
      section: primitive.space[5], // 64 — между карточкой и краем плашки
      page: primitive.space[6], //   96 — поля кадра
    },
    size: {
      hero: primitive.fontSize[5], //     92 — заголовок в две краски
      counter: primitive.fontSize[4], //  68 — цифра счётчика
      subtitle: primitive.fontSize[3], // 42 — плашка-субтитр
      cardTitle: primitive.fontSize[2], //36 — заголовок карточки
      row: primitive.fontSize[1], //      32 — строка списка
      label: primitive.fontSize[0], //    24 — подпись счётчика
    },
    weight: primitive.weight,
    radius: primitive.radius,
  }) as const;

export type PromoTheme = ReturnType<typeof semantic>;

// ── Уровень 3: компоненты ────────────────────────────────────────────────────
// Геометрия деталей. Все числа — из шкалы отступов либо кратны мини-юниту 8,
// потому что курсор и раскладка карточки считаются арифметикой, а не глазом.
export const component = {
  card: {
    width: 1120,
    padding: 48, // space.loose
    borderWidth: 2,
    headerHeight: 96,
    rowHeight: 88,
    hairlineHeight: 2,
    top: 296, // 8 × 37 — карточка стоит выше плашки-субтитра с запасом
  },
  badge: {
    height: 96,
    paddingInline: 32,
  },
  cursor: {
    size: 48,
    // Курсор ведёт по строкам списка: 12 кадров на переезд (≈400 мс — расстояние
    // в сотню пикселей), 10 кадров стоит на строке. Дольше переезд — вязко,
    // короче — глаз не успевает за целью.
    travelFrames: 12,
    dwellFrames: 10,
  },
  subtitleBar: {
    bottom: 64, // space.section
    paddingBlock: 24,
    paddingInline: 48,
    maxWidth: 1440,
    radius: 16,
  },
  // Хореография: появление и уход. Кривые — IBM Carbon, продуктивный регистр.
  // Баунса нет: ни одна кривая не выходит за диапазон 0..1 по вертикали.
  motion: {
    enterFrames: 9, // ≈300 мс — появление панели
    exitFrames: 6, //  ≈200 мс — уход, короче появления: за уходящим не следят
    riseDistance: 32, // space.normal — насколько подъезжает снизу текстовая панель
    // Поверхность (карточка) подъезжает заметнее: она набирает непрозрачность
    // почти сразу (см. surfaceOpacity), и без внятного хода её появление
    // читалось бы как мгновенная подстановка белого прямоугольника.
    surfaceRise: 96, // space.page
    entranceEasing: [0, 0, 0.38, 0.9] as const, // Carbon entrance, productive
    standardEasing: [0.2, 0, 0.38, 0.9] as const, // Carbon standard, productive
  },
} as const;
